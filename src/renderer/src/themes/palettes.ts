import { flavors } from '@catppuccin/palette'
import type { Theme } from './types'
const cat = (flavor: 'mocha' | 'macchiato' | 'frappe' | 'latte'): Theme => {
  const c = flavors[flavor].colors,
    light = flavor === 'latte'
  return {
    id: ('catppuccin-' + flavor) as Theme['id'],
    name: 'Catppuccin ' + flavors[flavor].name,
    light,
    colors: {
      bg: c.base.hex,
      panel: c.mantle.hex,
      rail: c.crust.hex,
      surface: c.surface0.hex,
      'surface-hover': c.surface1.hex,
      border: c.surface0.hex,
      text: c.text.hex,
      muted: c.subtext0.hex,
      dim: c.overlay1.hex,
      accent: c.mauve.hex,
      green: c.green.hex,
      red: c.red.hex,
      yellow: c.yellow.hex,
      'on-accent': c.base.hex,
    },
    ansi: [
      c.surface1.hex,
      c.red.hex,
      c.green.hex,
      c.yellow.hex,
      c.blue.hex,
      c.pink.hex,
      c.teal.hex,
      c.subtext1.hex,
      c.surface2.hex,
      c.red.hex,
      c.green.hex,
      c.yellow.hex,
      c.blue.hex,
      c.pink.hex,
      c.teal.hex,
      c.text.hex,
    ],
  }
}
function preset(
  id: Theme['id'],
  name: string,
  light: boolean,
  bg: string,
  panel: string,
  rail: string,
  surface: string,
  border: string,
  text: string,
  muted: string,
  accent: string,
  ansi: string[],
): Theme {
  return {
    id,
    name,
    light,
    colors: {
      bg,
      panel,
      rail,
      surface,
      'surface-hover': border,
      border,
      text,
      muted,
      dim: muted,
      accent,
      green: ansi[2],
      red: ansi[1],
      yellow: ansi[3],
      'on-accent': light ? '#ffffff' : rail,
    },
    ansi,
  }
}
